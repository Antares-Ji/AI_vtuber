const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { StreamerBrain } = require('../src/brain');
const { VoiceCallStore } = require('../src/runtime/voice-call-store');
const { buildRealtimeMessages } = require('../src/brain/realtime-context');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'context-isolation-'));
const options = { llmEnabled: false, memoryOptions: { databasePath: path.join(dir,'memory.db'), legacyPath: path.join(dir,'absent.json') }, storyOptions: { filePath: path.join(dir,'story.json') }, runtimeOptions: { filePath: path.join(dir,'runtime.json') } };
let brain = new StreamerBrain(options);
const item = (user,text,extra={}) => ({ user,text,type:'chat',...extra });
const commit = (input, text) => { const p=brain.prepareStreamReply(input); return brain.commitStreamReply(p.item,p.context,text); };
try {
  commit(item('A','下次约定一起研究音乐'), '你喜欢哪一首歌曲？');
  const a=brain.buildContext(item('A','继续'));
  const b=brain.buildContext(item('B','继续'));
  assert.match(a.cognition.conversation.pendingQuestion,/歌曲/);
  assert.equal(b.cognition.conversation.pendingQuestion,null);
  assert.equal(b.cognition.conversation.currentTopic,null);
  brain.cognition.conversation.pendingQuestion = '旧格式无归属问题';
  assert.equal(brain.buildContext(item('C','继续')).cognition.conversation.pendingQuestion,null);
  commit(item('B','下次约定一起画画'), '你喜欢哪一种颜色？');
  assert.match(brain.buildContext(item('A','继续')).cognition.conversation.pendingQuestion,/歌曲/);
  const pending=brain.prepareStreamReply(item('A','旧场在途'));
  brain.memoryStore.endCurrentSession();
  assert.throws(()=>brain.commitStreamReply(pending.item,pending.context,'旧回复'),{code:'STALE_REPLY'});
  assert.equal(brain.memoryStore.getSessionStatus().messageCount,0);
  assert.equal(brain.buildContext(item('A','继续')).cognition.conversation.pendingQuestion,null);

  commit(item('A','弹幕独占内容'), '弹幕独占回答');
  assert.equal(brain.buildContext(item('A','普通弹幕')).cognition.openLoops.length,0);
  const calls=new VoiceCallStore(brain.memoryStore);
  const one=calls.start({user:'A'}), two=calls.start({user:'A'});
  calls.record(one.id,{sequence:1,text:'第一通专属输入',reply:'第一通专属回答',status:'completed'});
  calls.record(two.id,{sequence:1,text:'被打断但听到的输入',status:'interrupted'});
  const voice=item('A','现在继续',{voiceCallId:two.id,voiceSequence:2,contextScope:`voice:${two.id}`});
  brain.memoryStore.db.prepare("UPDATE voice_call_turns SET reply_text = '不应视为已说出的残稿' WHERE call_id = ?").run(two.id);
  const context=brain.prepareStreamReply(voice).context;
  const messages=buildRealtimeMessages(voice,context);
  assert.deepEqual(context.recent.map(x=>x.text),['被打断但听到的输入']);
  assert.ok(messages.some(x=>x.role==='user'&&x.content==='被打断但听到的输入'));
  assert.ok(!messages.some(x=>x.role==='assistant'));
  assert.ok(!JSON.stringify(messages).includes('弹幕独占'));
  assert.ok(!JSON.stringify(messages).includes('第一通专属'));
  commit(voice,'第二通专属回答');
  assert.ok(!brain.buildContext(item('A','普通弹幕')).recent.some(x=>x.reply==='第二通专属回答'));

  commit(item('A','下次约定A隐私标记'), 'A隐私问题？');
  commit(item('B','下次约定B保留标记'), 'B保留问题？');
  const forgotten=brain.prepareStreamReply(item('A','在途A隐私'));
  brain.forgetUser('A');
  assert.throws(()=>brain.commitStreamReply(forgotten.item,forgotten.context,'不能恢复A'),{code:'STALE_REPLY'});
  assert.ok(!JSON.stringify(brain.cognition).includes('A隐私'));
  assert.ok(JSON.stringify(brain.cognition).includes('B保留'));
  brain.memoryStore.close();
  brain=new StreamerBrain(options);
  assert.ok(!JSON.stringify(brain.cognition).includes('A隐私'));
  assert.ok(JSON.stringify(brain.cognition).includes('B保留'));
  assert.ok(!brain.lastSpeech || brain.lastSpeech.item.user !== 'A');
  console.log('Context isolation passed: per viewer/session/call, interrupted inputs, stale commits, selective forget and restart.');
} finally { brain.memoryStore.close(); fs.rmSync(dir,{recursive:true,force:true}); }
