'use strict';
// BetterGI receives one standalone script; source modules stay reviewable.
const fs = require('node:fs');
const path = require('node:path');
const base = path.join(__dirname, 'story');
function buildStory() {
  const files = ['grounding.js', 'vision/template-diagnostics.js', 'vision/minimap-bearing.js', 'vision/post-action-position.js', 'macros/continuous-navigation.js', 'macros/travel-quest.js', 'native-runner.js'];
  return '// Generated by scripts/genshin/build-story.cjs. Edit story/ sources.\n' +
    files.map(name => `// Source: story/${name}\n${fs.readFileSync(path.join(base, name), 'utf8')}`).join('\n');
}
module.exports = { buildStory };
if (require.main === module) {
  const output = path.join(__dirname, 'story-main.js');
  const built = buildStory();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8') !== built) throw Error('story-main.js is stale; run node scripts/genshin/build-story.cjs');
  } else {
    fs.writeFileSync(output, built);
    console.log(output);
  }
}
